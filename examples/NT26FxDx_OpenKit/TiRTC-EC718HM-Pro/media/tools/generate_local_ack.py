#!/usr/bin/env python3
"""Generate the two local acknowledgement PCM assets with installed SAPI voices.

Windows + Python 3 only; no downloads or cloud credentials. Output WAV files
stay in --work-dir, outside the source tree. Only reviewed C samples and their
format/source hashes are written beside the product's playback module.
"""
from pathlib import Path
import argparse
import array
import hashlib
import json
import subprocess
import sys
import wave
import shutil


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--work-dir', type=Path, required=True)
    parser.add_argument('--powershell', default=shutil.which('pwsh.exe') or shutil.which('powershell.exe'),
                        help='PowerShell with System.Speech and both installed zh-CN voices')
    args = parser.parse_args()
    media = Path(__file__).resolve().parents[1]
    work = args.work_dir.resolve()
    if work == media or media in work.parents:
        raise ValueError('Keep temporary WAV files outside the product source tree')
    work.mkdir(parents=True, exist_ok=True)
    script = Path(__file__).with_name('synthesize_local_ack.ps1')
    # Execute the reviewed source as an ordinary command; do not change the
    # machine's script execution policy or install/register a speech engine.
    command = '& {\n' + script.read_text(encoding='utf-8') + '\n} -OutputDirectory ' + "'" + str(work).replace("'", "''") + "'"
    if not args.powershell:
        raise ValueError('PowerShell with System.Speech is required for regeneration')
    subprocess.run([args.powershell, '-NoProfile', '-Command', command], check=True, timeout=60)
    voices = {row['key']: row for row in json.loads((work/'voices.json').read_text(encoding='utf-8-sig'))}
    report = {'text': '我在', 'purpose': 'Local entry acknowledgement; not the cloud AI voice',
              'format': {'sample_rate': 16000, 'channels': 1, 'sample_bits': 16,
                         'encoding': 'signed little-endian PCM', 'frame_samples': 320},
              'source': 'Synthesized locally with installed Microsoft Windows SAPI voices; no speech-engine binaries are redistributed',
              'processing': {'silence_threshold_abs': 16, 'retained_leading_ms': 40,
                             'retained_trailing_ms': 100, 'padding': 'zero to a complete 20ms frame',
                             'amplitude_scaling': 'none'},
              'generators': {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                             for p in [Path(__file__), script]}, 'voices': []}
    output = ['/* Generated by media/tools/generate_local_ack.py. See local_ack_pcm.metadata.json. */']
    payloads = []
    for key in ('female','male'):
        wav = work/(key+'.wav')
        with wave.open(str(wav),'rb') as stream:
            assert (stream.getnchannels(),stream.getsampwidth(),stream.getframerate(),stream.getcomptype()) == (1,2,16000,'NONE')
            raw = stream.readframes(stream.getnframes())
        samples = array.array('h'); samples.frombytes(raw)
        if sys.byteorder != 'little': samples.byteswap()
        assert 0 < len(samples) <= 48000
        voiced = [i for i,value in enumerate(samples) if abs(value)>16]
        assert voiced, key
        begin = max(0,voiced[0]-640); end = min(len(samples),voiced[-1]+1+1600)
        kept = samples[begin:end]
        kept.extend([0]*((-len(kept)) % 320))
        assert len(kept)<=32000 and max(abs(value) for value in kept)>1000
        packed = array.array('h',kept)
        if sys.byteorder != 'little': packed.byteswap()
        payload = packed.tobytes(); payloads.append(payload)
        output.append(f'static const int16_t s_ack_{key}[] = {{')
        for offset in range(0,len(kept),16):
            output.append('    '+','.join(str(value) for value in kept[offset:offset+16])+',')
        output.append('};')
        report['voices'].append(dict(voices[key], samples=len(kept), pcm_bytes=len(payload),
            duration_ms=len(kept)//16, sha256=hashlib.sha256(payload).hexdigest(),
            source_wav_sha256=hashlib.sha256(wav.read_bytes()).hexdigest(),
            original_samples=len(samples), retained_range=[begin,end]))
    assert payloads[0] != payloads[1]
    (media/'local_ack_pcm.inc').write_text('\n'.join(output)+'\n',encoding='utf-8',newline='\n')
    (media/'local_ack_pcm.metadata.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8',newline='\n')
    print(json.dumps(report,ensure_ascii=False))


if __name__ == '__main__':
    main()
